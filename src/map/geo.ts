export interface GeoCountry {
  iso: string;
  nameEn: string;
  nameFa: string;
  engineId: string | null;
  note1946?: string;
  /** چندضلعی‌ها در مختصات جهان ۱۰۰۰×۵۰۰: هر چندضلعی فهرستی از حلقه‌هاست */
  polygons: [number, number][][][];
  centroid: [number, number];
  area: number;
}

const projection = geoNaturalEarth1().fitSize([WORLD_W, WORLD_H], { type: 'Sphere' } as never);

export function projectLonLat(lon: number, lat: number): [number, number] {
  const p = projection([lon, lat]);
  return p ? [p[0], p[1]] : [0, 0];
}

/** حلقه را در نقطه پرش ضد نصف‌النهار (روسیه/فیجی) می‌شکند تا خط افقی سراسری کشیده نشود */
export function splitRing(pts: [number, number][]): [number, number][][] {
  const out: [number, number][][] = [];
  let cur: [number, number][] = [];
  for (let i = 0; i < pts.length; i++) {
    if (i > 0 && Math.abs(pts[i][0] - pts[i - 1][0]) > WORLD_W / 2) {
      if (cur.length > 1) out.push(cur);
      cur = [];
    }
    cur.push(pts[i]);
  }
  if (cur.length > 1) out.push(cur);
  return out.length ? out : [pts];
}

function ringArea(ring: [number, number][]): number {
  let a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  }
  return Math.abs(a / 2);
}

function projectGeometry(geom: Geometry): [number, number][][][] {
  const polys: [number, number][][][] = [];
  const addPoly = (rings: Position[][]) => {
    const projected: [number, number][][] = [];
    for (const ring of rings) {
      const pts = ring.map(([lon, lat]) => projectLonLat(lon, lat));
      for (const seg of splitRing(pts)) projected.push(seg);
    }
    if (projected.length) polys.push(projected);
  };
  if (geom.type === 'Polygon') addPoly(geom.coordinates);
  else if (geom.type === 'MultiPolygon') geom.coordinates.forEach(addPoly);
  return polys;
}

/** آزمون نقطه در چندضلعی (ray casting) روی حلقه بیرونی */
export function pointInRing(x: number, y: number, ring: [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]; const [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function hitTest(countries: GeoCountry[], x: number, y: number): GeoCountry | null {
  // کوچک‌ترین چندضلعی برنده است (کشورهای کوچک روی بزرگ‌ها)
  let best: GeoCountry | null = null;
  for (const c of countries) {
    for (const poly of c.polygons) {
      if (poly[0] && pointInRing(x, y, poly[0])) {
        if (!best || c.area < best.area) best = c;
        break;
      }
    }
  }
  return best;
}

let cache: GeoCountry[] | null = null;

/** بارگذاری تنبل توپوجیسون Natural Earth و تبدیل به چندضلعی‌های پروجکت‌شده */
export async function loadWorldFeatures(): Promise<GeoCountry[]> {
  if (cache) return cache;
  const topo = (await import('world-atlas/countries-110m.json')).default as never;
  const fc = feature(topo, (topo as { objects: { countries: never } }).objects.countries) as unknown as FeatureCollection;
  const out: GeoCountry[] = [];
  for (const f of fc.features as Feature[]) {
    if (!f.geometry) continue;
    const iso = String(f.id ?? '').padStart(3, '0');
    const nameEn = (f.properties as { name?: string } | null)?.name ?? 'Unknown';
    const polygons = projectGeometry(f.geometry);
    if (!polygons.length) continue;
    const c = geoCentroid(f as never);
    const centroid = projectLonLat(c[0], c[1]);
    const area = polygons.reduce((s, p) => s + (p[0] ? ringArea(p[0]) : 0), 0);
    out.push({
      iso, nameEn, nameFa: NAME_FA[iso] ?? nameEn,
      engineId: ISO_TO_ENGINE[iso] ?? null,
      note1946: NOTE_1946[iso],
      polygons, centroid, area,
    });
  }
  out.sort((a, b) => b.area - a.area);
  cache = out;
  return out;
}
